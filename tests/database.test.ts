import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import nextEnv from '@next/env';
import { migrate } from '../lib/migrate';
import { getDatabase, createDatabase, closeDatabase } from '../lib/db';
import * as store from '../lib/store';
import { importJson } from '../lib/import-json';
nextEnv.loadEnvConfig(process.cwd());

test('PostgreSQL integration: accounts, concurrent rooms, messages, limits, presence, and import', { skip: !process.env.TEST_DATABASE_URL }, async () => {
  const admin = createDatabase(process.env.TEST_DATABASE_URL!);
  const schema = `hi_fie_test_${randomUUID().replaceAll('-', '')}`;
  const original = process.env.DATABASE_URL;
  const originalMigrationUrl = process.env.PRISMA_MIGRATION_URL;
  try {
    await admin.$executeRawUnsafe(`CREATE SCHEMA "${schema}"`);
    const url = new URL(process.env.TEST_DATABASE_URL!);
    url.searchParams.set('schema', schema);
    process.env.DATABASE_URL = url.toString();
    process.env.PRISMA_MIGRATION_URL = url.toString();
    await closeDatabase();
    await migrate();
    await migrate(); // Rerunning migrations must be safe.
    await store.register('Alice', 'alice@example.com', 'long-password');
    await assert.rejects(store.register('Other', 'ALICE@example.com', 'long-password'));
    assert.equal(await store.authenticate('alice@example.com', 'wrong'), null);
    const alice = await store.authenticate('alice@example.com', 'long-password');
    assert.ok(alice);
    await store.register('Bob', 'bob@example.com', 'long-password');
    const bob = await store.authenticate('bob@example.com', 'long-password');
    assert.ok(bob);
    const created = await store.createAndJoinRoom(alice);
    assert.match(created.code, /^[A-Z2-9]{5}$/);
    assert.ok(created.members.some(member => member.id === alice.id));
    const beforeFailure = await getDatabase().room.count();
    await assert.rejects(store.createAndJoinRoom({ id: randomUUID(), name: 'Old session' }), /sign out and sign in/);
    const afterFailure = await getDatabase().room.count();
    assert.equal(afterFailure, beforeFailure);
    const codes = await Promise.all(Array.from({ length: 30 }, () => store.createRoom()));
    assert.equal(new Set(codes).size, 30);
    const code = codes[0];
    assert.match(code, /^[A-Z2-9]{5}$/);
    await assert.rejects(store.send(code, alice, 'unauthorized'));
    await Promise.all(Array.from({ length: 5 }, () => store.join(code, alice)));
    assert.equal((await store.getRoom(code)).messages.filter(message => message.text === 'Alice joined the room.').length, 1);
    for (let i = 0; i < 7; i++) await store.send(code, alice, `message ${i}`);
    const joined = await store.join(code, bob);
    assert.equal(joined.history.length, 5);
    assert.equal(joined.history[0].text, 'message 2');
    await store.heartbeat(code, bob);
    await Promise.all(Array.from({ length: 5 }, (_, i) => store.send(code, bob, `concurrent ${i}`)));
    const room = await store.getRoom(code);
    assert.equal(room.messages.filter(message => message.text.startsWith('concurrent')).length, 5);
    await closeDatabase(); // A fresh app connection sees the persisted messages and presence.
    assert.equal((await store.getRoom(code)).messages.length, room.messages.length);
    assert.equal(store.members(await store.getRoom(code)).length, 2);
    const limits = await Promise.allSettled(Array.from({ length: 25 }, () => store.limit('concurrent-limit', 10)));
    assert.equal(limits.filter(result => result.status === 'fulfilled').length, 10);
    await store.leave(code, bob);
    assert.equal((await store.getRoom(code)).messages.at(-1)?.text, 'Bob left the room.');
    await getDatabase().member.updateMany({ where: { roomCode: code }, data: { seen: BigInt(Date.now() - 46000) } });
    const expired = await store.getRoom(code);
    assert.equal(store.members(expired).length, 0);
    assert.equal(expired.messages.at(-1)?.text, 'Alice left the room.');
    await store.cleanup();
    assert.equal((await store.getRoom(code)).messages.filter(message => message.text === 'Alice left the room.').length, 1);
    await getDatabase().room.update({ where: { code }, data: { updated: BigInt(Date.now() - 3600001) } });
    await store.cleanup();
    await assert.rejects(store.getRoom(code));
    const remaining = await getDatabase().message.count({ where: { roomCode: code } });
    assert.equal(remaining, 0);
    const legacyUser = { id: randomUUID(), name: 'Legacy', email: 'legacy@example.com', salt: 'salt', hash: '00'.repeat(64) };
    const legacyMessages = Array.from({ length: 100 }, (_, index) => ({ id: randomUUID(), name: 'Legacy', text: `Preserved message ${index}`, system: false, userId: index === 99 ? randomUUID() : legacyUser.id, at: Date.now() + index }));
    const data = { users: [legacyUser], rooms: { ABCDE: { code: 'ABCDE', updated: Date.now(), messages: legacyMessages, members: {} } } };
    const imported = await importJson(data);
    assert.deepEqual(imported, { users: 1, rooms: 1, messages: 100 });
    assert.deepEqual(await importJson(data), { users: 0, rooms: 0, messages: 0 });
    const importedRoom = await store.getRoom('ABCDE');
    assert.equal(importedRoom.messages.length, 100);
    assert.equal(importedRoom.messages[0].text, 'Preserved message 0');
    assert.equal(importedRoom.messages.at(-1)?.text, 'Preserved message 99');
    assert.equal(importedRoom.messages.at(-1)?.userId, null);
  } finally {
    await closeDatabase();
    if (!/^hi_fie_test_[a-f0-9]{32}$/.test(schema)) throw new Error('Invalid test schema.');
    await admin.$executeRawUnsafe(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
    await admin.$disconnect();
    if (originalMigrationUrl === undefined) delete process.env.PRISMA_MIGRATION_URL; else process.env.PRISMA_MIGRATION_URL = originalMigrationUrl;
    if (original === undefined) delete process.env.DATABASE_URL; else process.env.DATABASE_URL = original;
  }
});
